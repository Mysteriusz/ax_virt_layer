#include "i64_qtables.h"

#include "intel/i64_immd.h"
#include "intel/i64_modrm.h"

/*
 	For I64_IMMD_INT interface.
*/

u64 *L2I_MASK_LOOKUP[8] = {[0 ... 7] = L2I_MASK_DEFAULT};
u8 *L2I_SUBMASK_LOOKUP[8] = {[0 ... 7] = L2I_SUBMASK_DEFAULT};

u64 *L2M_MASK_LOOKUP[8] = {[0 ... 7] = L2M_MASK_DEFAULT};

u8 IMMD_MASK_LEN_TABLE[4] = {0};
u8 IMMD_SUBMASK_LEN_TABLE[4] = {0};

/*
 	For I64_INSTR interface.
*/
u8 MOD_DLEN_LOOKUP[4] = {[0 ... 3] = 0};
u8 LEG_PREF_LOOKUP[0xff] = {[0 ... 0xfe] = 0};
bool LEG_PREF_EXT_LOOKUP[0xff] = {[0 ... 0xfe] = 0};

/*
 	Quick table loaders
*/

void i64_load_qtables(
	void
){
	L2I_MASK_LOOKUP[0b111] = (u64*)IMMD_TABLES.l2_0f_mask; // 0fH & 7H = 111B
	L2I_MASK_LOOKUP[0b110] = (u64*)IMMD_TABLES.l2_66_mask; // 66H & 7H = 110B
	L2I_MASK_LOOKUP[0b001] = (u64*)IMMD_TABLES.l2_0f_mask; // f3H & 7H = 001B
	L2I_MASK_LOOKUP[0b010] = (u64*)IMMD_TABLES.l2_0f_mask; // f2H & 7H = 010B

	L2I_SUBMASK_LOOKUP[0b111] = (u8*)IMMD_TABLES.l2_0f_submask; // 0fH & 7H = 111B
	L2I_SUBMASK_LOOKUP[0b110] = (u8*)IMMD_TABLES.l2_66_submask; // 66H & 7H = 110B
	L2I_SUBMASK_LOOKUP[0b001] = (u8*)IMMD_TABLES.l2_0f_submask; // f3H & 7H = 001B
	L2I_SUBMASK_LOOKUP[0b010] = (u8*)IMMD_TABLES.l2_0f_submask; // f2H & 7H = 010B

	L2M_MASK_LOOKUP[0b111] = (u64*)MODRM_TABLES.l2_0f_mask; // 0fH & 7H = 111B
	L2M_MASK_LOOKUP[0b110] = (u64*)MODRM_TABLES.l2_66_mask; // 66H & 7H = 110B
	L2M_MASK_LOOKUP[0b001] = (u64*)MODRM_TABLES.l2_0f_mask; // f3H & 7H = 001B
	L2M_MASK_LOOKUP[0b010] = (u64*)MODRM_TABLES.l2_0f_mask; // f2H & 7H = 010B

	IMMD_MASK_LEN_TABLE[0b00] = 0; // No immediate
	IMMD_MASK_LEN_TABLE[0b01] = 1;
	IMMD_MASK_LEN_TABLE[0b10] = 4;
	IMMD_MASK_LEN_TABLE[0b11] = 0; // Submask should be accessed

	IMMD_SUBMASK_LEN_TABLE[0b00] = 0; // No immediate
	IMMD_SUBMASK_LEN_TABLE[0b01] = 2;
	IMMD_SUBMASK_LEN_TABLE[0b10] = 4;
	IMMD_SUBMASK_LEN_TABLE[0b11] = 8; 

	MOD_DLEN_LOOKUP[0b00] = 4;
	MOD_DLEN_LOOKUP[0b01] = 1;
	MOD_DLEN_LOOKUP[0b10] = 4;
	MOD_DLEN_LOOKUP[0b11] = 0;

	LEG_PREF_LOOKUP[0xf0] = 0xf0;
	LEG_PREF_LOOKUP[0xf2] = 0xf2;
	LEG_PREF_LOOKUP[0xf3] = 0xf3;
	LEG_PREF_LOOKUP[0x2e] = 0x2e;
	LEG_PREF_LOOKUP[0x36] = 0x36;
	LEG_PREF_LOOKUP[0x3e] = 0x3e;
	LEG_PREF_LOOKUP[0x26] = 0x26;
	LEG_PREF_LOOKUP[0x64] = 0x64;
	LEG_PREF_LOOKUP[0x65] = 0x65;
	LEG_PREF_LOOKUP[0x66] = 0x66;
	LEG_PREF_LOOKUP[0x67] = 0x67;

	LEG_PREF_EXT_LOOKUP[0x66] = 1;
	LEG_PREF_EXT_LOOKUP[0xf2] = 1;
	LEG_PREF_EXT_LOOKUP[0xf3] = 1;
}

